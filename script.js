/* =====================================================
   HERO PARTICLES
===================================================== */
function createParticles() {
    const container = document.getElementById('heroParticles');
    if (!container) return;
    
    for (let i = 0; i < 30; i++) {
        const particle = document.createElement('div');
        const size = Math.random() * 4 + 2;
        const x = Math.random() * 100;
        const y = Math.random() * 100;
        const duration = Math.random() * 10 + 6;
        const delay = Math.random() * 5;
        
        particle.style.cssText = `
            position: absolute;
            width: ${size}px;
            height: ${size}px;
            background: rgba(245, 237, 228, ${Math.random() * 0.25 + 0.05});
            border-radius: 50%;
            top: ${y}%;
            left: ${x}%;
            animation: floatParticle ${duration}s ease-in-out infinite alternate;
            animation-delay: ${delay}s;
            pointer-events: none;
        `;
        container.appendChild(particle);
    }
}

const particleStyles = document.createElement('style');
particleStyles.textContent = `
    @keyframes floatParticle {
        0% { transform: translate(0, 0) scale(1); opacity: 0.2; }
        100% { transform: translate(${Math.random() * 80 - 40}px, ${Math.random() * 80 - 40}px) scale(1.8); opacity: 0.7; }
    }
`;
document.head.appendChild(particleStyles);
createParticles();

/* =====================================================
   SMOOTH ANCHOR SCROLL
===================================================== */
document.querySelectorAll('a[href^="#"]').forEach(link => {
    link.addEventListener('click', e => {
        const targetId = link.getAttribute('href');
        if (targetId === '#') return;
        const target = document.querySelector(targetId);
        if (!target) return;
        e.preventDefault();
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
});

/* =====================================================
   ACTIVE NAV LINK
===================================================== */
const sections = document.querySelectorAll('section[id]');
const navLinks = document.querySelectorAll('.desktop-nav a');

window.addEventListener('scroll', () => {
    let current = '';
    sections.forEach(section => {
        const top = section.offsetTop - 150;
        if (window.scrollY >= top) {
            current = section.id;
        }
    });
    
    navLinks.forEach(link => {
        link.classList.remove('active');
        if (link.getAttribute('href') === `#${current}`) {
            link.classList.add('active');
        }
    });
});

