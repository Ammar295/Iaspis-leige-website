function updateAllText() {
    // Update all elements with data-key attributes
    document.querySelectorAll('[data-key]').forEach(el => {
        const key = el.dataset.key;
        const translation = getText(key);
        if (translation) {
            // Check if element has child nodes
            const hasChildElements = el.children.length > 0;
            
            if (hasChildElements) {
                // Try to find and replace text nodes
                let textNodeFound = false;
                el.childNodes.forEach(node => {
                    if (node.nodeType === 3 && node.textContent.trim()) {
                        node.textContent = translation;
                        textNodeFound = true;
                    }
                });
                // If no text node found, create one
                if (!textNodeFound && el.children.length > 0) {
                    const textNode = document.createTextNode(' ' + translation);
                    el.insertBefore(textNode, el.firstChild);
                }
            } else {
                // Simple element with only text
                el.textContent = translation;
            }
        }
    });
    
    // Special handling for ALL headings with spans
    // Hero heading: "Sweet moments, made better."
    const heroHeading = document.querySelector('.hero h1');
    if (heroHeading) {
        const textNodes = [];
        const spanNodes = [];
        heroHeading.childNodes.forEach(node => {
            if (node.nodeType === 3) textNodes.push(node);
            if (node.nodeType === 1 && node.tagName === 'SPAN') spanNodes.push(node);
        });
        textNodes.forEach((node, index) => {
            if (node.textContent.trim()) {
                node.textContent = getText('heroHeading') + ' ';
            }
        });
        spanNodes.forEach(span => {
            span.textContent = getText('heroSpan');
        });
    }
    
    // About heading: "A little sweetness goes a long way."
    const aboutHeading = document.querySelector('.about h2');
    if (aboutHeading) {
        const textNodes = [];
        const spanNodes = [];
        aboutHeading.childNodes.forEach(node => {
            if (node.nodeType === 3) textNodes.push(node);
            if (node.nodeType === 1 && node.tagName === 'SPAN') spanNodes.push(node);
        });
        textNodes.forEach((node, index) => {
            if (node.textContent.trim()) {
                node.textContent = getText('aboutHeading') + ' ';
            }
        });
        spanNodes.forEach(span => {
            span.textContent = getText('aboutSpan');
        });
    }
    
    // Menu heading: "Something for every craving."
    const menuHeading = document.querySelector('.section-heading h2');
    if (menuHeading) {
        const textNodes = [];
        const spanNodes = [];
        menuHeading.childNodes.forEach(node => {
            if (node.nodeType === 3) textNodes.push(node);
            if (node.nodeType === 1 && node.tagName === 'SPAN') spanNodes.push(node);
        });
        textNodes.forEach((node, index) => {
            if (node.textContent.trim()) {
                node.textContent = getText('menuHeading') + ' ';
            }
        });
        spanNodes.forEach(span => {
            span.textContent = getText('menuSpan');
        });
    }
    
    // CTA heading: "Your next sweet moment awaits."
    const ctaHeading = document.querySelector('.cta h2');
    if (ctaHeading) {
        const textNodes = [];
        const spanNodes = [];
        ctaHeading.childNodes.forEach(node => {
            if (node.nodeType === 3) textNodes.push(node);
            if (node.nodeType === 1 && node.tagName === 'SPAN') spanNodes.push(node);
        });
        textNodes.forEach((node, index) => {
            if (node.textContent.trim()) {
                node.textContent = getText('ctaHeading') + ' ';
            }
        });
        spanNodes.forEach(span => {
            span.textContent = getText('ctaSpan');
        });
    }
    
    // Contact heading: "Let's make your day sweeter."
    const contactHeading = document.querySelector('.contact h2');
    if (contactHeading) {
        const textNodes = [];
        const spanNodes = [];
        contactHeading.childNodes.forEach(node => {
            if (node.nodeType === 3) textNodes.push(node);
            if (node.nodeType === 1 && node.tagName === 'SPAN') spanNodes.push(node);
        });
        textNodes.forEach((node, index) => {
            if (node.textContent.trim()) {
                node.textContent = getText('contactHeading') + ' ';
            }
        });
        spanNodes.forEach(span => {
            span.textContent = getText('contactSpan');
        });
    }
    
    // Update order buttons
    document.querySelectorAll('.order-button').forEach(btn => {
        const icon = btn.querySelector('i');
        const textContent = getText('addOrder');
        if (icon) {
            btn.innerHTML = '';
            const textNode = document.createTextNode(textContent + ' ');
            btn.appendChild(textNode);
            btn.appendChild(icon);
        } else {
            btn.innerHTML = textContent + ' <i class="ri-add-line"></i>';
        }
    });
    
    // Update checkout button
    const checkoutBtn = document.querySelector('.checkout-button');
    if (checkoutBtn) {
        const icon = checkoutBtn.querySelector('i');
        const text = getText('checkout');
        if (icon) {
            checkoutBtn.innerHTML = '';
            checkoutBtn.appendChild(icon);
            const textNode = document.createTextNode(' ' + text);
            checkoutBtn.appendChild(textNode);
        } else {
            checkoutBtn.innerHTML = text;
        }
    }
    
    // Update pay button
    const payBtn = document.querySelector('.pay-button');
    if (payBtn) {
        const icon = payBtn.querySelector('i');
        const text = getText('payNow');
        if (icon) {
            payBtn.innerHTML = '';
            payBtn.appendChild(icon);
            const textNode = document.createTextNode(' ' + text);
            payBtn.appendChild(textNode);
        } else {
            payBtn.innerHTML = text;
        }
    }
    
    // Update secure text
    const secureText = document.querySelector('.payment-secure span');
    if (secureText) {
        secureText.textContent = getText('secureText');
    }
    
    // Update cart total label
    const totalLabel = document.querySelector('.cart-total span');
    if (totalLabel) {
        totalLabel.textContent = getText('cartTotal');
    }
    
    // Update cart empty message
    const cartEmptyText = document.querySelector('.cart-empty p');
    if (cartEmptyText) {
        cartEmptyText.textContent = getText('cartEmpty');
    }
    
    // Update toast message
    const toastText = document.querySelector('.toast span');
    if (toastText) {
        toastText.textContent = getText('addedToast');
    }
    
    // Update cart title
    const cartTitle = document.querySelector('.cart-header h3');
    if (cartTitle) {
        cartTitle.textContent = getText('cartTitle');
    }
}

const langToggle = document.getElementById('langToggle');
const mobileLangToggle = document.getElementById('mobileLangToggle');

function toggleLanguage() {
    currentLanguage = currentLanguage === 'en' ? 'ar' : 'en';
    
    const langText = document.querySelector('.lang-text');
    const mobileLangText = mobileLangToggle?.querySelector('span');
    
    if (currentLanguage === 'ar') {
        if (langText) langText.textContent = 'AR';
        if (mobileLangText) mobileLangText.textContent = 'العربية';
        document.documentElement.dir = 'rtl';
        document.documentElement.lang = 'ar';
    } else {
        if (langText) langText.textContent = 'EN';
        if (mobileLangText) mobileLangText.textContent = 'English';
        document.documentElement.dir = 'ltr';
        document.documentElement.lang = 'en';
    }
    
    updateAllText();
}

langToggle?.addEventListener('click', toggleLanguage);
mobileLangToggle?.addEventListener('click', toggleLanguage);

