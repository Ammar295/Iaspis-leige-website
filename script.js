/* =====================================================
   CART SYSTEM
===================================================== */
let cart = [];
let currentLanguage = 'en';

function getText(key) {
    return translations[currentLanguage]?.[key] || translations.en[key] || key;
}

/* =====================================================
   CART FUNCTIONS
===================================================== */
function addToCart(item) {
    const existing = cart.find(c => c.id === item.id && c.size === item.size);
    if (existing) {
        existing.quantity += 1;
    } else {
        cart.push({ ...item, quantity: 1 });
    }
    updateCartUI();
    showToast(`${item.name}${item.size ? ` (${item.size})` : ''} ${getText('addedToast')}`);
}

function removeFromCart(index) {
    cart.splice(index, 1);
    updateCartUI();
}

function updateCartUI() {
    const cartItems = document.getElementById('cartItems');
    const cartCount = document.getElementById('cartCount');
    const cartTotal = document.getElementById('cartTotal');
    const paymentTotal = document.getElementById('paymentTotal');
    
    const totalItems = cart.reduce((sum, item) => sum + item.quantity, 0);
    cartCount.textContent = totalItems;
    
    if (totalItems > 0) {
        cartCount.classList.add('bump');
        setTimeout(() => cartCount.classList.remove('bump'), 400);
    }
    
    if (cart.length === 0) {
        cartItems.innerHTML = `
            <div class="cart-empty">
                <i class="ri-shopping-bag-line"></i>
                <p>${getText('cartEmpty')}</p>
            </div>
        `;
    } else {
        cartItems.innerHTML = cart.map((item, index) => `
            <div class="cart-item">
                <div class="cart-item-info">
                    <h4>${item.name}</h4>
                    <span>${item.size ? item.size + ' • ' : ''}x${item.quantity}</span>
                </div>
                <span class="cart-item-price">${(item.price * item.quantity).toFixed(2)} SAR</span>
                <button class="cart-item-remove" data-index="${index}">
                    <i class="ri-close-line"></i>
                </button>
            </div>
        `).join('');
        
        document.querySelectorAll('.cart-item-remove').forEach(btn => {
            btn.addEventListener('click', () => {
                removeFromCart(parseInt(btn.dataset.index));
            });
        });
    }
    
    const total = cart.reduce((sum, item) => sum + (item.price * item.quantity), 0);
    cartTotal.textContent = total.toFixed(2) + ' SAR';
    if (paymentTotal) paymentTotal.textContent = total.toFixed(2) + ' SAR';
}

/* =====================================================
   TOAST
===================================================== */
const toast = document.getElementById('toast');
let toastTimer;

function showToast(message) {
    toast.querySelector('span').textContent = message;
    toast.classList.add('show');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => {
        toast.classList.remove('show');
    }, 3000);
}

